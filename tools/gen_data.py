#!/usr/bin/env python3
"""Build src/data.c from the CSV tables in data/.

Game requirements name CPUs and cards the way a box does ("Pentium III 700",
"GeForce3"). This script resolves each name to a row in cpus.csv / gpus.csv
and stops with an error if it cannot, so the program never ships a broken link.
"""
import csv, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")


def rows(name):
    with open(os.path.join(DATA, name), newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


cpus = rows("cpus.csv")
gpus = rows("gpus.csv")
games = rows("games.csv")
years = rows("years.csv")
refs = {r["key"]: r["value"] for r in rows("refs.csv")}

cpu_by_name = {r["name"].lower(): i for i, r in enumerate(cpus)}
# box names that are not rows in the table: (family row to scale from, MHz)
CPU_ALIAS = {
    "core 2 duo e6400": ("Core 2 Duo E6600", 2133),
    "athlon 64 x2 4400+": ("Athlon 64 X2 4200+", 2200),
}
extra_cpus = []  # rows added for box names that fall between table rows


def resolve_cpu(name):
    key = name.strip().lower()
    if key in cpu_by_name:
        return cpu_by_name[key]
    if key in CPU_ALIAS:
        base, mhz = CPU_ALIAS[key]
        b = cpus[cpu_by_name[base.lower()]]
    else:
        m = re.match(r"^(.*\S)\s+(\d+)$", name.strip())
        if not m:
            sys.exit(f"cannot resolve CPU '{name}'")
        fam, mhz = m.group(1).lower(), int(m.group(2))
        cands = []
        for r in cpus:
            low = r["name"].lower()
            if not low.startswith(fam + " "):
                continue
            rest = low[len(fam) + 1:]
            if re.match(r"^[\d.]+[ace]?( ghz)?$", rest):
                cands.append(r)
        if not cands:
            sys.exit(f"cannot resolve CPU '{name}'")
        b = min(cands, key=lambda r: abs(int(r["mhz"]) - mhz))
    idx = float(b["index"]) * mhz / int(b["mhz"])
    row = {"name": name.strip(), "year": b["year"], "mhz": str(mhz), "cores": b["cores"],
           "index": f"{idx:.1f}", "est": "1", "hidden": True}
    cpus.append(row)
    cpu_by_name[key] = len(cpus) - 1
    return len(cpus) - 1


GPU_ALIAS = {"voodoo": "3dfx Voodoo Graphics", "tnt": "NVIDIA Riva TNT", "tnt2": "NVIDIA Riva TNT2"}


def resolve_gpu(name):
    key = name.strip().lower()
    if key in ("none", "svga 2mb", ""):
        return -1
    if key in GPU_ALIAS:
        key = GPU_ALIAS[key].lower()
    for i, r in enumerate(gpus):
        low = r["name"].lower()
        if low == key or low.endswith(" " + key):
            return i
    sys.exit(f"cannot resolve card '{name}'")


OS = {"95": 0, "98": 1, "2000": 2, "XP": 3, "XPSP2": 4}


def dx10(v):
    return int(round(float(v) * 10))


game_rows = []
for g in games:
    game_rows.append((g, resolve_cpu(g["min_cpu"]), resolve_cpu(g["rec_cpu"]),
                      resolve_gpu(g["min_gpu"]), resolve_gpu(g["rec_gpu"])))
game_rows.sort(key=lambda t: (int(t[0]["year"]), t[0]["name"].lower()))

# rows added for box names stay out of the comparison tables: put them last
visible = [r for r in cpus if not r.get("hidden")]
hidden = [r for r in cpus if r.get("hidden")]
order = visible + hidden
remap = {id(r): i for i, r in enumerate(order)}
old_index = {i: remap[id(r)] for i, r in enumerate(cpus)}

# report_build keeps per-game and per-year arrays on the stack, and the row
# structs use small field types; fail here rather than overflow at run time
if len(game_rows) > 256: sys.exit(f"{len(game_rows)} games: raise tiers[] in score.c")
if len(years) > 16: sys.exit(f"{len(years)} years: raise ys[] in score.c")
for g in games:
    if not 0 < float(g["disk_mb"]) <= 65535: sys.exit(f"disk_mb out of range for {g['name']}")
for r in gpus:
    if int(r["vram_mb"]) > 32767 or dx10(r["dx"]) > 255: sys.exit(f"field out of range for {r['name']}")

o = []
o.append("/* Generated by tools/gen_data.py from the CSV files in data. Do not edit. */")
o.append('#include "wb.h"\n')
o.append("const CpuRow g_cpus[] = {")
for r in order:
    o.append(f'  {{{cstr(r["name"])}, {round(float(r["index"]))}}},')
o.append("};")
o.append(f"const int g_ncpus = {len(visible)};  /* rows after this are box names used by games */\n")

o.append("const GpuRow g_gpus[] = {")
for r in gpus:
    o.append(f'  {{{cstr(r["name"])}, {cstr(r["match"].lower())}, {r["vram_mb"]}, {round(float(r["index"]))}, {dx10(r["dx"])}}},')
o.append("};")
o.append(f"const int g_ngpus = {len(gpus)};\n")

o.append("const GameRow g_games[] = {")
for g, mc, rc, mg, rg in game_rows:
    o.append(f'  {{{cstr(g["name"])}, {g["year"]}, '
             f'{old_index[mc]}, {g["min_ram"]}, {mg}, '
             f'{old_index[rc]}, {g["rec_ram"]}, {rg}, '
             f'{int(float(g["disk_mb"]))}, {OS[g["os"]]}, {dx10(g["min_dx"])}, {g["est"]}}},')
o.append("};")
o.append(f"const int g_ngames = {len(game_rows)};\n")

o.append("const YearRow g_years[] = {")
for y in years:
    c = cpus[cpu_by_name[y["cpu"].lower()]]
    gi = resolve_gpu(y["gpu"])
    desc = f'{y["cpu"]}, {y["ram_desc"]}, {gpus[gi]["name"]}, {y["disk_desc"]}'
    o.append(f'  {{{cstr(desc)}, {y["year"]}, {round(float(c["index"]))}, {round(float(gpus[gi]["index"]))}, {y["ram_score"]}, {y["disk_score"]}}},')
o.append("};")
o.append(f"const int g_nyears = {len(years)};\n")

for k in ["REF_DMIPS", "REF_MWIPS", "REF_MEM_READ", "REF_MEM_WRITE", "REF_MEM_COPY",
          "REF_DISK_READ", "REF_DISK_WRITE", "REF_DISK_ACCESS", "REF_FILL", "REF_TRIS"]:
    o.append(f"const double {k} = {float(refs[k])};")
o.append(f'const char *REF_DESC = {cstr(refs["REF_DESC"])};')

with open(os.path.join(ROOT, "src", "data.c"), "w", encoding="utf-8") as f:
    f.write("\n".join(o) + "\n")
print(f"data.c: {len(visible)} CPUs (+{len(hidden)} box names), {len(gpus)} cards, {len(game_rows)} games, {len(years)} years")
