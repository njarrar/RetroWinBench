/* RetroWinBench: shared declarations */
#ifndef WB_H
#define WB_H

#define WIN32_LEAN_AND_MEAN
#include <windows.h>
#include <stdarg.h>

#define WB_VERSION "1.1"

/* ---- tiny runtime (rt.c): we link without the C runtime ---- */
void  *memset(void *d, int c, unsigned n);
void  *memcpy(void *d, const void *s, unsigned n);
void  *memmove(void *d, const void *s, unsigned n);
int    strcmp(const char *a, const char *b);
char  *strcpy(char *d, const char *s);
unsigned strlen(const char *s);
int    rt_strncasecmp(const char *a, const char *b, unsigned n);
const char *rt_stristr(const char *hay, const char *needle);
int    rt_vfmt(char *out, int cap, const char *f, va_list ap);
int    rt_fmt(char *out, int cap, const char *f, ...);
double rt_sqrt(double x);
double rt_sin(double x);
double rt_cos(double x);
double rt_atan(double x);
double rt_log(double x);
double rt_exp(double x);
double rt_pow(double x, double y);
void  *rt_alloc(unsigned n);       /* page-aligned, zeroed */
void   rt_free(void *p);
unsigned rt_rand(void);

/* ---- timing ---- */
double now_sec(void);

/* ---- system info (sysinfo.c) ---- */
typedef struct {
    char os_name[96];
    int  os_major, os_minor, os_build, os_sp, os_is_nt;
    char dx_text[32];
    double dx_ver;          /* installed DirectX runtime, e.g. 9.3 for 9.0c */
    char cpu_vendor[16];
    char cpu_name[64];
    int  has_cpuid, has_tsc, has_mmx, has_sse, has_sse2;
    int  cores;
    double cpu_mhz;
    unsigned ram_mb;
    char adapter[128];      /* display adapter name from Windows */
    int  glide;             /* 3dfx Glide driver found */
    char temp_dir[MAX_PATH];
    double disk_free_mb;
} SysInfo;
void sysinfo_get(SysInfo *si);

/* ---- benchmarks ---- */
typedef void (*ProgressFn)(const char *msg);

typedef struct { double dmips, mwips; } CpuResult;
void bench_cpu(CpuResult *r, ProgressFn p);

typedef struct { double read_mbs, write_mbs, copy_mbs; unsigned block_kb; } MemResult;
void bench_mem(MemResult *r, unsigned ram_mb, ProgressFn p);

typedef struct {
    int ok; char err[128];
    double read_mbs, write_mbs, access_ms;
    unsigned file_mb; int unbuffered;
} DiskResult;
void bench_disk(DiskResult *r, const char *dir, double free_mb, unsigned ram_mb, ProgressFn p);

typedef struct {
    int ok; char err[128];
    char vendor[64], renderer[128], version[64];
    int software;           /* Microsoft "GDI Generic" or similar */
    double fill_mpix, mtris;
    double dx_guess;        /* feature level guessed from GL extensions */
} GpuResult;
void bench_gpu(GpuResult *r, HINSTANCE inst, ProgressFn p);

/* ---- built-in reference data (data.c, generated by tools/gen_data.py) ---- */
typedef struct { const char *name; short index; } CpuRow;
typedef struct { const char *name, *match; short vram, index; unsigned char dx10; } GpuRow;
typedef struct {
    const char *name;
    short year, min_cpu, min_ram, min_gpu, rec_cpu, rec_ram, rec_gpu;
    unsigned short disk_mb;
    unsigned char os, min_dx10, est;    /* os: 0=95/98 1=98 2=2000/XP 3=XP 4=XP SP2 */
} GameRow;
typedef struct { const char *desc; short year, cpu, gpu, ram, disk; } YearRow;

extern const CpuRow  g_cpus[];  extern const int g_ncpus;
extern const GpuRow  g_gpus[];  extern const int g_ngpus;
extern const GameRow g_games[]; extern const int g_ngames;
extern const YearRow g_years[]; extern const int g_nyears;

/* reference PC (score 100) measured figures */
extern const double REF_DMIPS, REF_MWIPS;
extern const double REF_MEM_READ, REF_MEM_WRITE, REF_MEM_COPY;
extern const double REF_DISK_READ, REF_DISK_WRITE, REF_DISK_ACCESS;
extern const double REF_FILL, REF_TRIS;
extern const char  *REF_DESC;

/* ---- scoring and report (score.c) ---- */
typedef struct {
    SysInfo si; CpuResult cpu; MemResult mem; DiskResult disk; GpuResult gpu;
    double s_cpu, s_mem, s_disk, s_gpu, s_total;
    int gpu_row;            /* identified card row or -1 */
    double gpu_game_index;  /* index used for game checks */
    double gpu_dx;          /* feature level used for game checks */
} Results;
void score_compute(Results *r);
int  report_build(Results *r, char *out, int cap);

#endif
